# template/README.md: upstream's guide, renamed, with "Under the hood" at the end.

BOXFAB_SDK = "0.1.0a4"  # the BoxFab SDK version the build scripts are installed with

TEMPLATE_README_EXACT = [
    ("E2B_API_KEY=e2b_***", "BOXFAB_API_KEY=e2b_***", 2),
    # upstream's CI and releases build the template; here BoxFab builds it by hand
    ("This is the script CI and releases run.", "BoxFab builds the platform template with it.", 1),
    ("`template/.env` with your `E2B_API_KEY`", "`template/.env` with your `BOXFAB_API_KEY`", 1),
    ("[custom sandbox template](https://e2b.dev/docs/template/quickstart).",
     "custom sandbox template, as described below.", 1),
    ("1. Install E2B SDK\n", "1. Install the BoxFab SDKs\n", 1),
    ("pip install e2b dotenv\n", "pip install boxfab boxfab-code-interpreter dotenv\n", 1),
    ("from e2b import Template\n", "from boxfab import Template\n", 1),
    # upstream's two fixes (UPSTREAM.md, "Rewrites"): build.py is run as a script, so the template
    # module is imported absolutely; run_code is in the code interpreter SDK, not the core SDK.
    ("from .template import template\n", "from template import template\n", 1),
    ("from e2b import Template, default_build_logger\n", "from boxfab import Template, default_build_logger\n", 1),
    ("from e2b import Sandbox\n", "from boxfab_code_interpreter import Sandbox\n", 1),
]


def sync_template_readme(up: Path):
    text = (up / "template/README.md").read_text()
    for old, new, count in TEMPLATE_README_EXACT:
        n = text.count(old)
        if n != count:
            sys.exit(f"template/README.md: expected {count} x {old[:60]!r}, found {n}")
        text = text.replace(old, new)
    footer = (ROOT / "overlay/template-readme/footer.md").read_text()
    (OUT / "README.md").write_text(NOTICE_MD + text.rstrip("\n") + "\n" + footer)


# --------------------------------------------------------------------------------------------
# README.md: our introduction (note, "What is BoxFab?", steps 1-2), upstream's step 3 and
# "Customizing the sandbox template", renamed (upstream's docs and cookbook steps are left out);
# Under the hood and License.

README_STEP3 = ("### 3. Execute code with code interpreter inside Sandbox\n", "### 4. Check docs\n")
README_CUSTOMIZE = "## Customizing the sandbox template\n"
README_RULES = [
    (r"'@e2b/code-interpreter'", "'@boxfab/code-interpreter'", 1),
    (r"\be2b_code_interpreter\b", "boxfab_code_interpreter", 1),
]


def sync_readme(up: Path):
    text = (up / "README.md").read_text()
    start, end = README_STEP3
    if text.count(start) != 1 or text.count(end) != 1 or text.count(README_CUSTOMIZE) != 1:
        sys.exit("README.md: upstream's section headings changed")
    step3 = text[text.index(start):text.index(end)]
    for rx, repl, count in README_RULES:
        step3, n = re.subn(rx, repl, step3)
        if n != count:
            sys.exit(f"README.md step 3 {rx!r}: {n} matches, expected {count}")
    customize = text[text.index(README_CUSTOMIZE):].rstrip("\n") + "\n"
    o = ROOT / "overlay/readme"
    (ROOT / "README.md").write_text(
        NOTICE_MD + (o / "header.md").read_text() + step3 + customize + (o / "footer.md").read_text())


