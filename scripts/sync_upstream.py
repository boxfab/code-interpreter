# tests/: upstream's end-to-end tests of the template's server, with the BoxFab SDK.

TESTS_SKIP = {"package.json", "uv.lock", "__pycache__", ".venv"}
TESTS_IMPORTS = 6
TESTS_EXACT = [
    ("tests/conftest.py", 'os.getenv("E2B_DEBUG", "false")', 'os.getenv("BOXFAB_DEBUG", "false")', 1),
    ("tests/conftest.py", 'os.getenv("E2B_TESTS_TEMPLATE")', 'os.getenv("BOXFAB_TESTS_TEMPLATE")', 1),
    ("tests/pyproject.toml", 'name = "e2b-code-interpreter-tests"', 'name = "boxfab-code-interpreter-tests"', 1),
    ("tests/pyproject.toml", "HTTP-level test suite for the E2B Code Interpreter template",
     "HTTP-level test suite for the BoxFab Code Interpreter template", 1),
    ("tests/pyproject.toml", '"e2b>=2.32.0,<3",', f'"boxfab>={BOXFAB_SDK},<0.2",', 1),
    ("tests/pyproject.toml", "(E2B_DEBUG=true)", "(BOXFAB_DEBUG=true)", 1),
    ("tests/README.md", "the `e2b` SDK from `E2B_TESTS_TEMPLATE`", "the `boxfab` SDK from `BOXFAB_TESTS_TEMPLATE`", 1),
    ("tests/README.md", "E2B_API_KEY=... uv run pytest", "BOXFAB_API_KEY=... uv run pytest", 1),
    ("tests/README.md", "Set `E2B_DEBUG=true`", "Set `BOXFAB_DEBUG=true`", 1),
    ("tests/.env.example", "E2B_API_KEY=\n", "BOXFAB_API_KEY=\n", 1),
    ("tests/.env.example", "# Optional, defaults to e2b.app\nE2B_DOMAIN=\n", "# Optional, defaults to us-west.boxfab.dev\nBOXFAB_DOMAIN=\n", 1),
    ("tests/.env.example", "E2B_TESTS_TEMPLATE=\n", "BOXFAB_TESTS_TEMPLATE=\n", 1),
    ("tests/.env.example", "E2B_DEBUG=\n", "BOXFAB_DEBUG=\n", 1),
]


def sync_tests(up: Path):
    out = ROOT / "tests"
    lock = (out / "uv.lock").read_bytes() if (out / "uv.lock").exists() else None
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(up / "tests", out, ignore=shutil.ignore_patterns(*TESTS_SKIP))
    if lock is not None:
        (out / "uv.lock").write_bytes(lock)
    n = 0
    for f in sorted(out.rglob("*.py")):
        text = f.read_text()
        new, k = re.subn(r"^from e2b import\b", "from boxfab import", text, flags=re.M)
        n += k
        if k:
            f.write_text(NOTICE_PY + new)
    if n != TESTS_IMPORTS:
        sys.exit(f"tests: {n} imports renamed, expected {TESTS_IMPORTS}")
    apply_exact(TESTS_EXACT)
    for f in out.rglob("*"):
        if f.is_file() and f.suffix in (".py", ".toml", ".md") or f.name == ".env.example":
            for i, line in enumerate(f.read_text().splitlines(), 1):
                if re.search(r"^\s*(from|import) e2b\b(?!_)|\bE2B_(API_KEY|DOMAIN|DEBUG|TESTS_TEMPLATE)\b|e2b\.app", line):
                    sys.exit(f"{f.relative_to(ROOT)}:{i}: upstream name left: {line.strip()}")
    print(f"  tests: {sum(1 for _ in out.rglob('test_*.py'))} test files, {n} imports renamed")


def apply_exact(rules):
    for rel, old, new, expected in rules:
        p = ROOT / rel
        text = p.read_text()
        n = text.count(old)
        if n != expected:
            sys.exit(f"{rel}: expected {expected} x {old[:70]!r}, found {n}")
        p.write_text(text.replace(old, new))


README_FORBIDDEN = [
    (re.compile(r"\b(from|import) e2b\b(?!_)"), "e2b import"),
    (re.compile(r"\be2b_code_interpreter\b|@e2b/code-interpreter|\be2b-code-interpreter\b"), "upstream package name"),
    (re.compile(r"\bE2B_(API_KEY|DOMAIN)\b"), "E2B_* variable"),
    (re.compile(r"e2b\.dev|e2b\.app"), "E2B domain"),
    (re.compile(r"\bE2B\b"), "E2B name"),
]


def audit():
    problems = []
    # READMEs: only text that came from upstream is checked; our own text (overlay/) may name E2B
    # on purpose (Under the hood, License).
    own = {ln for f in (ROOT / "overlay").rglob("*.md") for ln in f.read_text().splitlines() if ln.strip()}
    own |= set(NOTICE_MD.splitlines())
    for p in (ROOT / "README.md", OUT / "README.md"):
        for i, line in enumerate(p.read_text().splitlines(), 1):
            if line in own:
                continue
            for rx, what in README_FORBIDDEN:
                if rx.search(line):
                    problems.append(f"{p.relative_to(ROOT)}:{i}: {what}: {line.strip()}")
    for name in SCRIPTS:
        p = OUT / name
        for i, line in enumerate(p.read_text().splitlines(), 1):
            for rx, what in FORBIDDEN:
                if rx.search(line):
                    problems.append(f"{p.relative_to(ROOT)}:{i}: {what}: {line.strip()}")
    if problems:
        sys.exit("audit failed:\n  " + "\n  ".join(problems))


def pin(name: str) -> str:
    m = re.search(rf"^- {name} commit: `([0-9a-f]{{40}})`", (ROOT / "UPSTREAM.md").read_text(), re.M)
    if not m:
        sys.exit(f"UPSTREAM.md has no '- {name} commit: `<sha>`' line")
    return m.group(1)


def checkout(url: str, ref: str, given: Path | None, tmp: Path, name: str) -> Path:
    if given is None:
        given = tmp / name
        subprocess.run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", url, str(given)], check=True)
        subprocess.run(["git", "-C", str(given), "checkout", "-q", ref], check=True)
    head = subprocess.run(["git", "-C", str(given), "rev-parse", "HEAD"], capture_output=True, text=True,
                          check=True).stdout.strip()
    if head != ref:
        sys.exit(f"{given} is at {head}, UPSTREAM.md pins {ref}")
    return given


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--code-interpreter", type=Path, dest="src",
                    help="e2b-dev/code-interpreter checkout at the pinned commit")
    a = ap.parse_args()
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        up = checkout(UPSTREAM, pin("Code interpreter repo"), a.src, Path(tmp), "code-interpreter")
        sync_template(up)
        sync_template_readme(up)
        sync_readme(up)
        sync_tests(up)
        shutil.copy2(up / "Makefile", ROOT / "Makefile")  # unchanged
        # The license is upstream's Apache-2.0 text, unchanged.
        if (ROOT / "LICENSE").read_text() != (up / "LICENSE").read_text():
            sys.exit("LICENSE differs from upstream's Apache-2.0 text")
    audit()
    print("sync OK")


if __name__ == "__main__":
    main()
