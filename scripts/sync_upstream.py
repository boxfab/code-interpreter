#!/usr/bin/env python3
"""Regenerate the template in this repository from the pinned e2b-dev/code-interpreter commit.

    python3 scripts/sync_upstream.py                             # clone the pinned commit
    python3 scripts/sync_upstream.py --code-interpreter <checkout>

Source (pin in UPSTREAM.md, checked against the checkout): e2b-dev/code-interpreter
    template/  -> template/ (all but package.json, upstream's release tooling; CHANGELOG.md is
                  kept as CHANGELOG-E2B.md)
    tests/     -> tests/ (all but package.json and uv.lock; uv.lock is this repository's own,
                  made with `uv lock` for the BoxFab SDK)
    Makefile   -> Makefile
    README.md  -> README.md (our introduction and steps 1-2 from overlay/readme/, upstream's
                  step 3 and "Customizing the sandbox template", Under the hood and License)

The SDKs are generated in boxfab/python-sdk and boxfab/js-sdk (code-interpreter/).

Generated paths are never edited by hand: change a rule here and re-run. Every rule asserts how
often it matched, so when upstream moves text the sync fails instead of shipping an E2B default.
A final audit fails on any `e2b` SDK import, E2B configuration variable or E2B domain left behind.
"""

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = "https://github.com/e2b-dev/code-interpreter.git"
OUT = ROOT / "template"

# Files derived from the Apache-2.0 upstream and changed here carry this notice (Apache-2.0
# section 4(b)).
NOTICE_PY = (
    "# Modified by ContextFab, Inc. for BoxFab: generated by scripts/sync_upstream.py\n"
    "# (see UPSTREAM.md). Licensed under Apache-2.0, see LICENSE.\n"
)

NOTICE_MD = (
    "<!-- Modified by ContextFab, Inc. for BoxFab: generated by scripts/sync_upstream.py from\n"
    "     e2b-dev/code-interpreter (Apache-2.0, see LICENSE and UPSTREAM.md). Do not edit by hand. -->\n"
)

SKIP = {"package.json"}  # upstream's release tooling
RENAME = {"CHANGELOG.md": "CHANGELOG-E2B.md"}

# The Python scripts the sync changes: the SDK import (e2b -> boxfab) and the E2B_* variables
# they read for configuration. Everything else in template/ is copied byte for byte.
SCRIPTS = ["template.py", "build_prod.py", "build_test.py", "build_ci.py", "build_debug.py",
           "build_docker.py", "debug_logs.py"]
EXPECT_IMPORTS = 7
CONFIG_VARS = ["TESTS_TEMPLATE", "DEBUG_TEMPLATE"]
EXPECT_VARS = 3

# template.py: the sandbox hostname. BoxFab's runtime names every sandbox e2b.local; until the
# platform-wide change lands, the template sets boxfab.local (the shell prompt reads user@boxfab).
# Not in the Docker variant, where the container's hostname belongs to Docker.
TEMPLATE_EXACT = [
    ('''    template = template.set_user("user").set_workdir("/home/user")
''', '''    # BoxFab: the sandbox hostname (UPSTREAM.md, "Rewrites")
    if not is_docker:
        template = template.run_cmd(
            [
                "hostname boxfab.local",
                "echo boxfab.local > /etc/hostname",
                "sed -i 's/^127\\\\.0\\\\.1\\\\.1\\\\s.*/127.0.1.1\\\\tboxfab.local/' /etc/hosts",
                "grep -q boxfab.local /etc/hosts"
                " || printf '127.0.1.1\\\\tboxfab.local\\\\n' >> /etc/hosts",
            ]
        )

    template = template.set_user("user").set_workdir("/home/user")
''', 1),
]

# What upstream's template keeps, checked so a silent upstream change is noticed: the alias and
# resources of the platform template, and the port the SDKs talk to.
EXPECT = [
    ("build_prod.py", 'alias="code-interpreter-v1"'),
    ("build_prod.py", "cpu_count=2"),
    ("build_prod.py", "memory_mb=2048"),
    ("build_test.py", 'alias="code-interpreter-dev"'),
    ("template.py", 'wait_for_url("http://localhost:49999/health")'),
]

# What must not remain in the changed scripts. Deliberately kept elsewhere (names internal to the
# sandbox, and runtime protocol): the `e2b/data` and `e2b/chart` output types, the e2b-charts
# package, /run/e2b-jupyter, E2B_LOCAL, the e2b-dev/ijavascript kernel; see UPSTREAM.md.
FORBIDDEN = [
    (re.compile(r"\b(from|import) e2b\b(?!_)"), "e2b import"),
    (re.compile(r"\bE2B_(API_KEY|DOMAIN|DEBUG|API_URL|SANDBOX_URL|" + "|".join(CONFIG_VARS) + r")\b"),
     "E2B_* variable"),
    (re.compile(r"e2b\.dev|e2b\.app"), "E2B domain"),
]


def sync_template(up: Path):
    src = up / "template"
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(exist_ok=True)
    for p in sorted(src.iterdir()):
        if p.name in SKIP or p.name == "__pycache__":
            continue
        dst = OUT / RENAME.get(p.name, p.name)
        if p.is_dir():
            shutil.copytree(p, dst, ignore=shutil.ignore_patterns("__pycache__"))
        else:
            shutil.copy2(p, dst)

    imports = variables = 0
    for name in SCRIPTS:
        p = OUT / name
        text = p.read_text()
        new, k = re.subn(r"^from e2b import\b", "from boxfab import", text, flags=re.M)
        imports += k
        new, k = re.subn(r"\bE2B_(" + "|".join(CONFIG_VARS) + r")\b", r"BOXFAB_\1", new)
        variables += k
        p.write_text(NOTICE_PY + new)
    if (imports, variables) != (EXPECT_IMPORTS, EXPECT_VARS):
        sys.exit(f"template scripts: {imports} imports, {variables} variables renamed; "
                 f"expected {EXPECT_IMPORTS} and {EXPECT_VARS}")
    apply_exact([("template/template.py", old, new, k) for old, new, k in TEMPLATE_EXACT])
    # The build dependencies: the BoxFab SDK instead of the E2B SDK.
    apply_exact([("template/requirements-dev.txt", "e2b==2.32.0\n", f"boxfab=={BOXFAB_SDK}\n", 1)])
    for name, needle in EXPECT:
        if needle not in (OUT / name).read_text():
            sys.exit(f"template/{name}: {needle} not found")
    # e2b-charts (template/charts) is MIT, with its own LICENSE, which must stay in place.
    if "MIT License" not in (OUT / "charts/LICENSE").read_text():
        sys.exit("template/charts/LICENSE is no longer the MIT license")
    n = sum(1 for p in OUT.rglob("*") if p.is_file())
    print(f"  template: {n} files, {imports} imports and {variables} variables renamed")


